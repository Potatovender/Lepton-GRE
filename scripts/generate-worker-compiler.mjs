import ts from "typescript";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

// Transitional bridge: retain the existing editor compiler intact, while producing
// an isolated worker module from its actual symbol dependencies, not text slicing.
const sourcePath = resolve("src/browser-preview-live.js");
const outputPath = resolve("src/compiler/scene-runtime.js");
const program = ts.createProgram([sourcePath], { allowJs: true, noResolve: true, target: ts.ScriptTarget.ESNext });
const file = program.getSourceFile(sourcePath), checker = program.getTypeChecker();
const declarations = new Map();
for (const statement of file.statements) {
  if (ts.isFunctionDeclaration(statement) && statement.name) declarations.set(checker.getSymbolAtLocation(statement.name), { name: statement.name.text, node: statement, statement });
  if (ts.isVariableStatement(statement)) for (const node of statement.declarationList.declarations) {
    if (ts.isIdentifier(node.name)) declarations.set(checker.getSymbolAtLocation(node.name), { name: node.name.text, node, statement });
  }
}
const byName = new Map([...declarations.values()].map((item) => [item.name, item]));
const seeds = ["validateSceneSync", "buildFragmentShader", "webGlShaderCacheKey", "sceneViewport", "displayViewportForSize", "resolveBackgroundColor", "drawPointsOverlay", "compileExpression", "buildRuntimeEnv", "sceneFunctionEnv", "evaluateScalarSetting", "timeVariableEntries", "timeUniformBindings", "expressionDependsOnCoordinates", "isValidViewport"];
const excluded = new Set(["scene", "latestDiagnostics", "viewport", "root"]);
const reached = new Set();
function visit(declaration) {
  if (!declaration || reached.has(declaration.name) || excluded.has(declaration.name)) return;
  reached.add(declaration.name);
  function walk(node) {
    if (ts.isIdentifier(node)) visit(declarations.get(checker.getSymbolAtLocation(node)));
    ts.forEachChild(node, walk);
  }
  walk(declaration.node);
}
for (const name of seeds) {
  if (!byName.has(name)) throw new Error(`Missing worker compiler entry point: ${name}`);
  visit(byName.get(name));
}
const statements = [...new Set([...reached].map((name) => byName.get(name).statement))].sort((a, b) => a.pos - b.pos);
const functions = [...reached].filter((name) => ts.isFunctionDeclaration(byName.get(name).node));
const imports = file.statements.filter((node) => ts.isImportDeclaration(node) && node.moduleSpecifier.text.startsWith("./math/"))
  .map((node) => node.getText(file).replace('"./math/', '"../math/'));
const constants = statements.filter((node) => ts.isVariableStatement(node) && !node.getText(file).startsWith("let activeCollectionGenerator"));
const degreeSetup = file.statements.find((node) => ts.isForOfStatement(node) && node.getText(file).includes("DEGREE_HELPER_NAMES"));
if (!degreeSetup) throw new Error("Missing degree-mode compiler initialization");
const bodies = statements.filter((node) => ts.isFunctionDeclaration(node) || node.getText(file).startsWith("let activeCollectionGenerator"))
  .map((node) => node.getText(file)).join("\n\n").replaceAll("window.__leptonForceGradient", "forceGradient").replace(/^[\t ]+$/gm, "");
if (/\b(?:window|document|localStorage|root)\s*\./.test(bodies)) throw new Error("Compiler now depends on DOM state; update the worker boundary explicitly");
const result = `// Generated by scripts/generate-worker-compiler.mjs. Do not edit by hand.\n${imports.join("\n")}\n\n${constants.map((node) => "export " + node.getText(file)).join("\n\n")}\n${degreeSetup.getText(file)}\n\nexport function createSceneRuntime(getScene = null, getForceGradient = () => false) {\n  let scene = structuredClone(DEFAULT_SCENE);\n  let forceGradient = false;\n  let latestDiagnostics = null;\n\n${bodies}\n\n  const methods = {\n    ${functions.join(",\n    ")},\n    validateScene: validateSceneSync\n  };\n  return {\n    setScene(next) { scene = next; },\n    getScene() { return scene; },\n    ...Object.fromEntries(Object.entries(methods).map(([name, fn]) => [name, (...args) => {\n      if (getScene) scene = getScene();\n      forceGradient = getForceGradient();\n      return fn(...args);\n    }]))\n  };\n}\n`;
if (process.argv.includes("--write")) {
  await writeFile(outputPath, result);
  console.log("Generated isolated worker compiler; editor source was not changed.");
} else {
  if (await readFile(outputPath, "utf8") !== result) throw new Error("Worker compiler is stale. Run node scripts/generate-worker-compiler.mjs --write, then run the parity tests.");
  console.log("Worker compiler matches the editor source.");
}
